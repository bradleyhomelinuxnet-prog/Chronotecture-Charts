#!/usr/bin/env python3
"""Bundle text/pNNN.txt (cleaned transcriptions of the text plates) into text/texts.js.

The plate viewer and the atlas search load texts.js with a <script> tag, so the
transcriptions work when the site is opened from disk as well as when it is served.
Run from the repository root: python3 tools/build_texts.py
"""
import glob, json, os, re

out = {}
for path in sorted(glob.glob('text/p[0-9][0-9][0-9].txt')):
    n = int(re.search(r'p(\d{3})\.txt$', path).group(1))
    out[n] = open(path, encoding='utf-8').read().strip('\n')

with open('text/texts.js', 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build_texts.py from text/pNNN.txt; do not edit by hand.\n')
    f.write('window.CHRONO_TEXT=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'text/texts.js: {len(out)} plates, {os.path.getsize("text/texts.js")} bytes')
